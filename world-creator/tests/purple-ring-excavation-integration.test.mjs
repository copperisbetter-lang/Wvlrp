// Verifies geometry/collision math and protected features on isolated purple ring branch.
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const js=readFileSync(new URL('../base-camp/purple-ring-excavation.js',import.meta.url),'utf8');
const mod=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const {excavatedHeight,excavationAt,cutMetrics,installPurpleRingExcavation,PURPLE_RING}=mod;
const base=(x,z)=>7*Math.sin(x/92)*Math.cos(z/78)+3*Math.sin(z/34)+2*Math.cos(x/43);
const terrain=(x,z)=>excavatedHeight(x,z,base(x,z));
const core=cutMetrics(base);
console.log('Purple ring 300°–344° 2.6m flat tread:',core);
assert.ok(core.coreGradePass,'Core exceeds 8% longitudinal or 3% tread cross-slope');
assert.ok(core.maxCoreCutMeters>3.4&&core.maxCoreCutMeters<3.65,'Expected hillside excavation');
assert.equal(PURPLE_RING.radius,268.224);
assert.equal(PURPLE_RING.treadHalfWidth,1.3);
for(const angle of [300,305,316,330,344]){
 const a=angle*Math.PI/180;
 const H=(off)=>terrain((PURPLE_RING.radius+off)*Math.cos(a),(PURPLE_RING.radius+off)*Math.sin(a));
 assert.ok(Math.abs(H(-1.3)-H(+1.3))<1e-5,'2.6m tread must be level at '+angle);
}
for(const [x,z] of [[0,-108],[0,0],[317.861133,-169.009763],[-280,-220],[160,100]]){
 assert.ok(Math.abs(terrain(x,z)-base(x,z))<1e-9,'Protected feature altered');
}
const a=320*Math.PI/180;
const H=(off)=>terrain((PURPLE_RING.radius+off)*Math.cos(a),(PURPLE_RING.radius+off)*Math.sin(a));
assert.ok(H(2.8)<(H(2.3)+H(3.3))*.5,'Swale must be genuine depression, not a decorative line');
const separation=Math.abs(Math.hypot(317.861133,-169.009763)-PURPLE_RING.radius);
assert.ok(separation>90,'Relocated campsite 64 must remain well outside excavation shoulders');
